#!/usr/bin/env python3
"""
HELIX Glue Context Publisher

Step 6 of the HELIX Context Route. Publishes approved context to the AWS Glue
Data Catalog using generally available APIs: table description, column
comments, and helix.* table parameters. Runs as a dry run unless --apply is
given, and prints every change first.

Sources (pick one):
    --pack templates/context/generated/glue-business-context.json
        HELIX silver tables, generated by tools/build_context_pack.py
    --review definition-review.csv
        approved rows from the steward review sheet for custom or historical
        tables (status = approved). steward_definition and
        steward_classification are used; anything not approved is skipped.

Targets:
    default      boto3 glue.get_table / glue.update_table
    --emit-sql   write Spark SQL (ALTER TABLE ... ALTER COLUMN ... COMMENT and
                 SET TBLPROPERTIES) instead, for Iceberg tables where catalog
                 updates should go through the table format. Tables in Amazon
                 S3 Tables are managed through the Iceberg engine; VALIDATE in
                 your account which path applies.

Glue business context (preview) fields such as glossary terms are carried in
the pack but not written by this tool, since the preview API may change.

Usage:
    python tools/apply_glue_context.py --pack templates/context/generated/glue-business-context.json \
        --database helix_silver                       # dry run
    python tools/apply_glue_context.py --pack ... --database helix_silver --apply
    python tools/apply_glue_context.py --review approved.csv --database legacy_bronze --apply
    python tools/apply_glue_context.py --pack ... --emit-sql context.sql

Requires boto3 for catalog updates (not for --emit-sql) and AWS credentials
with glue:GetTable and glue:UpdateTable on the target database.
"""
import argparse
import csv
import json
import sys

TABLE_INPUT_KEYS = ["Name", "Description", "Owner", "LastAccessTime", "LastAnalyzedTime", "Retention",
                    "StorageDescriptor", "PartitionKeys", "ViewOriginalText", "ViewExpandedText",
                    "TableType", "Parameters", "TargetTable", "ViewDefinition"]
MAX_COMMENT = 255
LEVELS = ["public", "internal", "confidential", "restricted"]


def from_pack(path):
    with open(path) as fh:
        pack = json.load(fh)
    out = []
    for t in pack.get("tables", []):
        out.append({"table": t["table"], "description": t.get("description", ""),
                    "parameters": t.get("table_parameters", {}),
                    "columns": {c["name"]: c.get("description", "") for c in t.get("columns", [])}})
    return out


def from_review(path):
    tables = {}
    with open(path, newline="", encoding="utf-8-sig") as fh:
        for r in csv.DictReader(fh):
            if (r.get("status") or "").strip().lower() != "approved":
                continue
            definition = (r.get("steward_definition") or "").strip()
            if not definition:
                print(f"skip {r.get('review_id')}: approved but no steward_definition", file=sys.stderr)
                continue
            proposed = (r.get("proposed_classification") or "internal").strip().lower()
            final = (r.get("steward_classification") or proposed).strip().lower()
            if final in LEVELS and proposed in LEVELS and LEVELS.index(final) < LEVELS.index(proposed):
                print(f"skip {r.get('review_id')}: classification lowered from {proposed} to {final}; "
                      f"needs data trustee sign-off (govern/context-governance-policy.json)", file=sys.stderr)
                continue
            t = tables.setdefault(r["source_table"].lower(), {"table": r["source_table"].lower(), "description": "",
                                                              "parameters": {"helix.context_source": "steward_review"},
                                                              "columns": {}})
            t["columns"][r["column_name"].lower()] = definition
            level = final if final in LEVELS else proposed
            cur = t["parameters"].get("helix.classification", "public")
            if LEVELS.index(level) > LEVELS.index(cur):
                t["parameters"]["helix.classification"] = level
            if (r.get("helix_link") or "").strip():
                t["parameters"].setdefault("helix.links", "")
                t["parameters"]["helix.links"] = ";".join(
                    x for x in (t["parameters"]["helix.links"].split(";") + [f"{r['column_name'].lower()}={r['helix_link'].strip()}"]) if x)
    return list(tables.values())


def sql_quote(s):
    return (s or "").replace("'", "''")


def emit_sql(items, database, path):
    lines = [f"-- HELIX context for {database}. Spark SQL for Apache Iceberg tables. Review before running."]
    for t in items:
        fq = f"{database}.{t['table']}"
        if t["description"]:
            lines.append(f"ALTER TABLE {fq} SET TBLPROPERTIES ('comment' = '{sql_quote(t['description'][:1000])}');")
        if t["parameters"]:
            props = ", ".join(f"'{k}' = '{sql_quote(str(v))}'" for k, v in t["parameters"].items())
            lines.append(f"ALTER TABLE {fq} SET TBLPROPERTIES ({props});")
        for c, d in t["columns"].items():
            if d:
                lines.append(f"ALTER TABLE {fq} ALTER COLUMN {c} COMMENT '{sql_quote(d[:MAX_COMMENT])}';")
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"Wrote {len(lines) - 1} statements to {path}")


def apply_glue(items, database, catalog_id, do_apply):
    try:
        import boto3
    except ImportError:
        sys.exit("boto3 is required for catalog updates; use --emit-sql otherwise")
    glue = boto3.client("glue")
    changed = missing = 0
    for t in items:
        kw = {"DatabaseName": database, "Name": t["table"]}
        if catalog_id:
            kw["CatalogId"] = catalog_id
        try:
            cur = glue.get_table(**kw)["Table"]
        except glue.exceptions.EntityNotFoundException:
            print(f"  missing: {database}.{t['table']}")
            missing += 1
            continue
        ti = {k: cur[k] for k in TABLE_INPUT_KEYS if k in cur}
        diffs = []
        if t["description"] and ti.get("Description") != t["description"]:
            ti["Description"] = t["description"]
            diffs.append("description")
        params = dict(ti.get("Parameters", {}))
        for k, v in t["parameters"].items():
            if params.get(k) != str(v):
                params[k] = str(v)
                diffs.append(k)
        ti["Parameters"] = params
        sd = ti.get("StorageDescriptor", {})
        for col in sd.get("Columns", []) + ti.get("PartitionKeys", []):
            d = t["columns"].get(col["Name"].lower())
            if d and col.get("Comment") != d[:MAX_COMMENT]:
                col["Comment"] = d[:MAX_COMMENT]
                diffs.append(f"column {col['Name']}")
        if not diffs:
            continue
        changed += 1
        print(f"  {'update' if do_apply else 'would update'} {database}.{t['table']}: {', '.join(diffs[:8])}"
              + (f" (+{len(diffs) - 8} more)" if len(diffs) > 8 else ""))
        if do_apply:
            upd = {"DatabaseName": database, "TableInput": ti}
            if catalog_id:
                upd["CatalogId"] = catalog_id
            glue.update_table(**upd)
    print(f"\nTables {'updated' if do_apply else 'to update'}: {changed}; not found: {missing}")
    if not do_apply:
        print("Dry run. Re-run with --apply to write.")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--pack")
    src.add_argument("--review")
    ap.add_argument("--database", required=True)
    ap.add_argument("--catalog-id", default="")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--emit-sql", default="")
    args = ap.parse_args()
    items = from_pack(args.pack) if args.pack else from_review(args.review)
    print(f"{len(items)} tables with context")
    if args.emit_sql:
        emit_sql(items, args.database, args.emit_sql)
    else:
        apply_glue(items, args.database, args.catalog_id, args.apply)


if __name__ == "__main__":
    main()
